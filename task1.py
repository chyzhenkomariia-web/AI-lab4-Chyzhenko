"""Завдання 1. Звичайний і просунутий prompt для однієї задачі:
визначення основних ідей і ключових понять тексту."""
from llm_client import send_prompt, read_text

TASK = "task1"
text = read_text("short_text.txt")

# Варіант 1. Звичайний prompt
simple_prompt = f"Визнач основні ідеї цього тексту.\n\n{text}"
send_prompt(TASK, "Варіант 1. Звичайний prompt", simple_prompt)

# Варіант 2. Просунутий prompt: роль + контекст + етапи + обмеження + формат
system = ("Ти методист курсу «Основи штучного інтелекту». Ти готуєш матеріали "
          "до семінару для студентів 2 курсу: пишеш точно, коротко й без зайвих вступів.")

advanced_prompt = f"""Контекст: текст нижче студенти прочитають перед семінаром про обмеження великих мовних моделей. Потрібна опорна шпаргалка для викладача.

Виконай задачу поетапно:
1. Тема: одне речення.
2. Ключові ідеї: 3-5 пунктів, кожен до 20 слів.
3. Основні поняття: таблиця з колонками «Поняття | Визначення за текстом» (3-5 рядків).
4. Питання для обговорення на семінарі: 2 питання, на які текст не дає однозначної відповіді.
5. Висновок: не більше 2 речень.

Обмеження:
- використовуй лише інформацію з тексту, нічого не додавай від себе;
- відокремлюй факти від думки автора (думку позначай словами «на думку автора»);
- мова: українська; загальний обсяг до 220 слів;
- без вступу та заключних фраз на кшталт «Сподіваюся, це допоможе».

Формат: Markdown, кожен етап з підзаголовком ###.

Текст:
{text}"""
send_prompt(TASK, "Варіант 2. Просунутий prompt", advanced_prompt, system=system)
