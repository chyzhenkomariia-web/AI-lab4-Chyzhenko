"""Завдання 3. Імітація ReAct (без справжнього агента та інструментів).

Структура: задача -> план дій -> виконання (Думка / Дія / Спостереження)
-> перевірка -> результат. Для порівняння те саме питання ставиться без структури.
"""
from llm_client import send_prompt, read_text

TASK = "task3"
text = read_text("short_text.txt")
QUESTION = ("Чи стверджує автор, що RAG повністю розв'язує проблему галюцинацій? "
            "Які твердження тексту є фактами, а які — висновками автора?")

# те саме питання без структури
send_prompt(TASK, "1. Без структури", f"{QUESTION}\n\nТекст:\n{text}")

react_prompt = f"""Ти аналітик, який перевіряє твердження за текстом. Працюй у стилі ReAct і суворо дотримуйся етапів.

ЗАДАЧА: {QUESTION}

ЕТАП 1. ПЛАН. Сформулюй 3-4 кроки аналізу та критерії: чим факт відрізняється від висновку автора.

ЕТАП 2. ВИКОНАННЯ. Для кожного кроку плану пиши трійку:
  Думка: що я зараз хочу з'ясувати;
  Дія: ЦИТУВАТИ(«...») — дослівна цитата з тексту, яку я перевіряю;
  Спостереження: що ця цитата показує.
Використовуй лише дію ЦИТУВАТИ, інших інструментів немає.

ЕТАП 3. ПЕРЕВІРКА. Чи всі речення тексту враховано? Чи немає цитат, яких насправді немає в тексті? Чи правильно визначено маркери думки автора («на мою думку», «очевидно», «ймовірно»)? Виправ помилки, якщо є.

ЕТАП 4. РЕЗУЛЬТАТ.
  а) коротка відповідь на перше питання (1-2 речення);
  б) таблиця «№ | Твердження | Факт / Висновок автора | Підстава».

Обмеження: використовуй лише текст нижче, без зовнішніх знань.

Текст:
{text}"""
send_prompt(TASK, "2. Імітація ReAct", react_prompt)
