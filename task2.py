"""Завдання 2. Декомпозиція складної задачі.

Задача: на основі тексту скласти пам'ятку для розробника навчального
чат-бота «Як зменшити галюцинації». Розв'язуємо двома способами:
  А) ланцюжок із 4 послідовних prompt (результат кожного кроку йде в наступний);
  Б) один загальний prompt.
"""
from llm_client import send_prompt, read_text

TASK = "task2"
text = read_text("short_text.txt")

SYSTEM = ("Ти інженер, який розробляє навчальні чат-боти на основі LLM. "
          "Спирайся на наданий текст, відповідай українською, стисло.")

# Декомпозиція: 4 кроки
problems = send_prompt(TASK, "Крок 1. Проблеми",
    "Випиши з тексту всі проблеми або ризики, пов'язані з відповідями LLM. "
    f"Нумерований список, по одному реченню.\n\nТекст:\n{text}",
    system=SYSTEM)

causes = send_prompt(TASK, "Крок 2. Причини",
    "Для кожної проблеми зі списку вкажи причину її виникнення так, як вона "
    "описана в тексті. Якщо в тексті причини немає, напиши «у тексті не вказано».\n\n"
    f"Проблеми:\n{problems}\n\nТекст:\n{text}",
    system=SYSTEM)

solutions = send_prompt(TASK, "Крок 3. Способи зменшення ризиків",
    "Для кожної проблеми запропонуй 2 практичні дії для розробника чат-бота. "
    "Познач, чи дія згадана в тексті («з тексту»), чи є твоєю пропозицією («додатково»).\n\n"
    f"Проблеми та причини:\n{causes}",
    system=SYSTEM)

memo = send_prompt(TASK, "Крок 4. Підсумкова пам'ятка",
    "Склади з матеріалів нижче пам'ятку для розробника: таблиця "
    "«Проблема | Причина | Що зробити | Пріоритет (високий/середній/низький)» "
    "і під нею 3 головні правила одним реченням кожне.\n\n"
    f"Проблеми та причини:\n{causes}\n\nСпособи зменшення ризиків:\n{solutions}",
    system=SYSTEM)

# Один загальний prompt для тієї самої задачі
send_prompt(TASK, "Один загальний prompt",
    "На основі тексту склади пам'ятку для розробника навчального чат-бота про те, "
    "як зменшити галюцинації: таблиця «Проблема | Причина | Що зробити | Пріоритет» "
    f"і 3 головні правила.\n\nТекст:\n{text}",
    system=SYSTEM)
